test('direct mode has no AI region and reduced motion disables the rotating effect', async ({ page, request }, info) => {
  await page.route('**/config.json', route => route.fulfill({ json: { llm: false, enabled: false, model: '', timeout_s: 3 } }))
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/monitor')
  await page.getByLabel('命令输入').fill('status')
  await page.getByRole('button', { name: '发送指令' }).click()
  await expect(page.getByRole('status')).toContainText('命令批次已执行')
  await expect(page.getByLabel('AI 输出历史')).toHaveCount(0)
  expect(await page.locator('.halo-spectrum').evaluate(element => getComputedStyle(element).opacity)).toBe('0')
  await page.screenshot({ path: info.outputPath('direct-glass.png') })
  await page.unroute('**/config.json')
  await request.post(`${api}/test/stream-hold`)
  await page.reload()
  await page.getByLabel('自然语言指令').fill('流式等待 查询状态')
  await page.getByLabel('自然语言指令').press('Enter')
  await expect(page.locator('.composer-shell')).toHaveAttribute('data-phase', 'streaming')
  expect(await page.locator('.halo-spectrum').evaluate(element => getComputedStyle(element, '::before').animationName)).toBe('none')
  await request.post(`${api}/test/stream-release`)
  await expect(page.getByRole('status')).toContainText('已执行')
})

for (const llm of [true, false]) test(`toolbar pause/resume works without AI requests (llm=${llm})`, async ({ page, request }, info) => {
  if (!llm) await page.route('**/config.json', route => route.fulfill({ json: { llm: false, enabled: false, model: '', timeout_s: 3 } }))
  const calls: { name: string; arguments: Record<string, unknown> }[] = []
  page.on('request', req => {
    if (req.url().endsWith('/mcp') && req.method() === 'POST') {
      const body = req.postDataJSON()
      if (body.method === 'tools/call') calls.push(body.params)
    }
  })
  await page.goto('/monitor')
  await page.getByRole('button', { name: '恢复', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('已恢复策略运行')
  await expect(page.getByRole('button', { name: '暂停', exact: true })).toBeEnabled()
  expect((await (await request.get(`${rc}/health`)).json()).control_owner).toBe('policy')
  await page.getByRole('button', { name: '暂停', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('已暂停策略运行')
  const after = await (await request.get(`${rc}/health`)).json()
  expect(after.state).toBe('paused')
  expect(after.control_owner).toBe('policy')
  await page.getByRole('button', { name: '复位', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('复位指令已完成')
  expect((await (await request.get(`${rc}/health`)).json()).control_owner).toBe('policy')
  expect(calls.filter(call => call.name === 'tui_command').map(call => call.arguments.text)).toEqual(['resume', 'pause', 'reset'])
  expect(calls.filter(call => ['take', 'return', 'command', 'return_and_wait'].includes(call.name))).toEqual([])
  expect((await (await request.get(`${api}/test/requests`)).json())).toEqual([])
  await page.setViewportSize({ width: 320, height: 740 })
  await expect(page.getByRole('button', { name: '恢复', exact: true })).toBeInViewport()
  await expect(page.getByRole('button', { name: '复位', exact: true })).toBeInViewport()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: info.outputPath('toolbar-mobile.png') })
})
