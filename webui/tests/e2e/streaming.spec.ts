import { expect, test } from '@playwright/test'
const api = process.env.RC_WEBUI_TEST_API || 'http://127.0.0.1:18766'
const rc = process.env.RC_WEBUI_E2E_URL || 'http://127.0.0.1:18765'

test.beforeEach(async ({ request }) => { expect((await request.post(`${api}/test/reset`)).ok()).toBeTruthy() })

test('streams visible explanation before DONE, then executes with orange and one green completion', async ({ page, request }, info) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await request.post(`${api}/test/stream-hold`)
  await page.goto('/monitor')
  await expect(page.locator('.camera-state[data-state=live]')).toHaveCount(3)
  await expect(page.getByLabel('AI 输出历史')).toHaveCount(0)
  const before = await (await request.get(`${rc}/health`)).json()
  await page.getByLabel('自然语言指令').fill('流式等待 复位')
  await page.getByRole('button', { name: '发送指令' }).click()
  const shell = page.locator('.composer-shell')
  await expect(shell).toHaveAttribute('data-phase', 'streaming')
  await expect(page.getByLabel('AI 输出历史')).toContainText('完整确认指令后')
  await expect(page.locator('.ai-answer')).toContainText('流式等待 复位')
  const generating = await (await request.get(`${rc}/health`)).json()
  expect(generating.generation).toBe(before.generation)
  expect((await (await request.get(`${api}/test/requests`)).json())[0].stream).toBe(true)
  await page.screenshot({ path: info.outputPath('streaming-desktop.png') })
  await request.post(`${api}/test/stream-release`)
  await expect(shell).toHaveAttribute('data-phase', 'executing')
  await expect(page.getByText('上一条操作需要确认', { exact: true })).toHaveCount(0)
  await page.screenshot({ path: info.outputPath('executing-desktop.png') })
  await expect(shell).toHaveAttribute('data-phase', 'success')
  await page.screenshot({ path: info.outputPath('success-desktop.png') })
  await expect(shell).toHaveAttribute('data-phase', 'idle')
  await expect(page.getByRole('status')).toContainText('已执行')
  expect(errors).toEqual([])
})

test('retains page history, lets readers scroll back and keeps mobile controls reachable', async ({ page, request }, info) => {
  await page.goto('/monitor')
  const input = page.getByLabel('自然语言指令')
  await input.fill('长输出 查询状态')
  await page.getByRole('button', { name: '发送指令' }).click()
  await expect(page.getByRole('status')).toContainText('已执行')
  const log = page.getByLabel('AI 输出历史')
  await log.evaluate(element => { element.scrollTop = 0; element.dispatchEvent(new Event('scroll')) })
  await expect(page.getByRole('button', { name: '回到最新' })).toBeVisible()
  await request.post(`${api}/test/stream-hold`)
  await input.fill('流式等待 查询状态')
  await page.getByRole('button', { name: '发送指令' }).click()
  await expect(page.locator('.ai-entry')).toHaveCount(2)
  await expect(page.locator('.composer-shell')).toHaveAttribute('data-phase', 'streaming')
  expect(await log.evaluate(element => element.scrollTop)).toBeLessThan(10)
  await page.getByRole('button', { name: '回到最新' }).click()
  await expect(page.getByRole('button', { name: '回到最新' })).toHaveCount(0)
  await request.post(`${api}/test/stream-release`)
  await expect(page.getByRole('status')).toContainText('已执行')
  for (const width of [320, 390, 768]) {
    await page.setViewportSize({ width, height: 844 })
    await expect(input).toBeInViewport()
    await expect(page.getByRole('tab', { name: '监控' })).toBeInViewport()
    await expect(page.getByRole('button', { name: '回到最新' })).toHaveCount(0)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.getByTestId('camera-right_wrist').scrollIntoViewIfNeeded()
    await expect(page.getByTestId('camera-right_wrist')).toBeInViewport()
    await page.screenshot({ path: info.outputPath(`history-${width}.png`) })
  }
  await page.getByRole('button', { name: '展开操作回执' }).click()
  await input.fill('查询状态')
  await page.getByRole('button', { name: '发送指令' }).click()
  await expect(log).toBeVisible()
  await expect(page.getByRole('status')).toContainText('已执行')
  await page.reload()
  await expect(page.getByLabel('AI 输出历史')).toHaveCount(0)
})

